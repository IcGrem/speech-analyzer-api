import re

# патерн для получения диалогов типа
# [Менеджер и клиент]
# [Разговор коллег c клиентом]
PATTERN_MANAGERS_CLIENT = re.compile(
    r"""
    (                                           # Начало всей захватываемой группы
        (?:                                     # Варианты формата метки "Тип разговора"
            \*\*Тип\sразговора:\*\*             # **Тип разговора:**
            | \[                                # [Менеджер и клиент] [Разговор коллег c клиентом]
            | ^                                 # или начало строки
            | \n                                # или просто новая строка
        )
        \s*(?:                                  # Основная фраза: "Менеджер и клиент" или "Разговор коллег с клиентом"
            Менеджер\sи\sклиент
            |
            Разговор\sколлег\sс\sклиентом)
        \s*                             
        (?:                                     # Закрывающая скобка/новая строка/конец
            \]
            |\n
            |$)                     

        .*?                                     # Всё до заголовка диалога
        \*\*Форматированный\sдиалог\s#\d+:\*\*  # Заголовок диалога обязательно

        .*?                                     # Всё до первой черты "---"
        (?:---\s*.*?)*                          # блоки "---" (0 или больше раз)                               
        .*?                                     # Сам диалог

    )                                           # Конец всей группы
    (?=                                         # Lookahead: конец блока
        \*\*Тип\sразговора:                   # либо начало следующего блока
        | \Z                                    # либо конец текста
    )
    """, re.DOTALL | re.VERBOSE | re.IGNORECASE
)

